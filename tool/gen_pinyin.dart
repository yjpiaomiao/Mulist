// Generates lib/core/pinyin/pinyin_data.dart from pinyin-data v0.15.0
// (tool/data/pinyin.txt, MIT, https://github.com/mozillazg/pinyin-data).
//
//   dart run tool/gen_pinyin.dart
//
// Per character (U+3400..U+9FFF and U+3007) the table keeps the primary
// reading and at most two other readings, tones removed, "ü" written "v".
import 'dart:io';

const _first = 0x3400;
const _last = 0x9FFF;

// Primary readings that differ from the data's first entry; chosen for how
// the characters usually appear in titles and artist names.
const _primaryOverrides = {
  '长': 'chang',
  '曾': 'zeng',
  '似': 'si',
  '柏': 'bai',
  '查': 'cha',
  '单': 'dan',
  '朴': 'piao',
  '仇': 'qiu',
  '翟': 'zhai',
  '解': 'xie',
  '尉': 'yu',
  '区': 'ou',
};

const _tones = {
  'ā': 'a', 'á': 'a', 'ǎ': 'a', 'à': 'a', //
  'ē': 'e', 'é': 'e', 'ě': 'e', 'è': 'e', 'ế': 'e', 'ề': 'e', 'ê': 'e',
  'ī': 'i', 'í': 'i', 'ǐ': 'i', 'ì': 'i',
  'ō': 'o', 'ó': 'o', 'ǒ': 'o', 'ò': 'o',
  'ū': 'u', 'ú': 'u', 'ǔ': 'u', 'ù': 'u',
  'ǖ': 'v', 'ǘ': 'v', 'ǚ': 'v', 'ǜ': 'v', 'ü': 'v',
  'ń': 'n', 'ň': 'n', 'ǹ': 'n', 'ḿ': 'm', 'm̀': 'm',
};

String toneless(String s) {
  final b = StringBuffer();
  for (final ch in s.split('')) {
    b.write(_tones[ch] ?? ch);
  }
  return b.toString().replaceAll('̄', '').replaceAll('̀', '').replaceAll('̌', '');
}

void main() {
  final lines = File('tool/data/pinyin.txt').readAsLinesSync();
  final readings = <int, List<String>>{};
  final re = RegExp(r'^U\+([0-9A-F]+): ([^#]+)#');
  for (final l in lines) {
    final m = re.firstMatch(l);
    if (m == null) continue;
    final cp = int.parse(m.group(1)!, radix: 16);
    if (!(cp == 0x3007 || (cp >= _first && cp <= _last))) continue;
    final list = <String>[];
    for (final r in m.group(2)!.trim().split(',')) {
      final t = toneless(r.trim());
      if (!RegExp(r'^[a-z]+$').hasMatch(t)) throw StateError('bad reading $r -> $t at U+${m.group(1)}');
      if (!list.contains(t)) list.add(t);
    }
    final ch = String.fromCharCode(cp);
    final o = _primaryOverrides[ch];
    if (o != null) {
      list.remove(o);
      list.insert(0, o);
    }
    readings[cp] = list.take(3).toList();
  }
  final syllables = <String>{for (final l in readings.values) ...l}.toList()..sort();
  final index = {for (var i = 0; i < syllables.length; i++) syllables[i]: i};

  String esc(int v) => '\\u${v.toRadixString(16).padLeft(4, '0')}';
  final primary = StringBuffer();
  final alts = StringBuffer();
  var altCount = 0;
  for (var cp = _first; cp <= _last; cp++) {
    final r = readings[cp];
    primary.write(r == null ? esc(0) : esc(index[r[0]]! + 1));
    if (r != null && r.length > 1) {
      alts
        ..write(esc(cp - _first))
        ..write(esc(index[r[1]]! + 1))
        ..write(esc(r.length > 2 ? index[r[2]]! + 1 : 0));
      altCount++;
    }
  }
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_pinyin.dart from pinyin-data 0.15.0 (MIT,')
    ..writeln('// https://github.com/mozillazg/pinyin-data). Do not edit.')
    ..writeln('// ignore_for_file: lines_longer_than_80_chars')
    ..writeln()
    ..writeln('const int pinyinFirst = 0x${_first.toRadixString(16)};')
    ..writeln('const int pinyinLast = 0x${_last.toRadixString(16)};')
    ..writeln('const int pinyinLingIndex = ${index['ling']! + 1};')
    ..writeln()
    ..writeln('/// Toneless syllables; tables store index + 1 (0 = no reading).')
    ..writeln('const List<String> pinyinSyllables = [')
    ..writeln(syllables.map((s) => "'$s'").join(', '))
    ..writeln('];')
    ..writeln()
    ..writeln('/// Primary reading of each code point from [pinyinFirst].')
    ..writeln("const String pinyinPrimary = '$primary';")
    ..writeln()
    ..writeln('/// $altCount triples (code point - [pinyinFirst], alt1, alt2), sorted.')
    ..writeln("const String pinyinAlternates = '$alts';");
  File('lib/core/pinyin/pinyin_data.dart').writeAsStringSync(out.toString());
  stdout.writeln('${readings.length} chars, ${syllables.length} syllables, $altCount polyphones');
}
